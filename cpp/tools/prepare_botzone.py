"""
Package DouMH C++ source files for Botzone submission.

Usage:
    python prepare_botzone.py              # Create staging dir + zip
    python prepare_botzone.py --amalgamate # Create single-file amalgamation
    python prepare_botzone.py --check      # Check file completeness only

Output (default):
    botzone_submit/
        main.cpp           # Main entry
        game_state.h       # State management
        card_encoding.h    # Card encoding + cards2array
        card_defs.h        # Card/Level types
        combo.h            # Combo detection + comparison
        move_generator.h   # 17 combo types enumeration
        legal_moves.h      # Legal move filtering
        feature_encoder.h  # Feature encoding bridge
        model_inference.h  # LibTorch inference
        jsoncpp/           # JSON library
            json.h
            json-forwards.h
        jsoncpp.cpp

Botzone submission steps:
    1. Select compiler: "带很多库" (LibTorch 1.5.0)
    2. Upload botzone_submit.zip
    3. Upload .pt models to User Storage
    4. MODEL_DIR = "data/models" (Botzone storage path)
"""
import os
import sys
import shutil
import zipfile

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SRC_DIR = os.path.join(SCRIPT_DIR, "..", "src")
OUTPUT_DIR = os.path.join(SCRIPT_DIR, "..", "botzone_submit")

# Files needed for compilation (in dependency order, though it doesn't matter)
SOURCES = [
    "main.cpp",
    "game_state.h",
    "card_encoding.h",
    "card_defs.h",
    "combo.h",
    "move_generator.h",
    "legal_moves.h",
    "feature_encoder.h",
    "model_inference.h",
    "oracle.h",
    "oracle.cpp",
    "opponent_modeling.h",
]

JSONCPP = [
    os.path.join("jsoncpp", "json.h"),
    os.path.join("jsoncpp", "json-forwards.h"),
    "jsoncpp.cpp",
]

MODEL_FILES = [
    "first_jit.pt",
    "second_jit.pt",
    "third_jit.pt",
    "landlord_jit.pt",
    "landlord_up_jit.pt",
    "landlord_down_jit.pt",
]

AMALGAMATE_ORDER = [
    "card_defs.h",
    "combo.h",
    "move_generator.h",
    "legal_moves.h",
    "card_encoding.h",
    "game_state.h",
    "oracle.h",
    "opponent_modeling.h",
    "feature_encoder.h",
    "model_inference.h",
]

AMALGAMATE_CPP = [
    "oracle.cpp",
]


def check_files():
    """Verify all required source files exist."""
    missing = []
    for f in SOURCES + JSONCPP:
        path = os.path.join(SRC_DIR, f)
        if not os.path.exists(path):
            missing.append(f)
    if missing:
        print("ERROR: Missing files:")
        for f in missing:
            print(f"  - {f}")
        return False
    print("All source files present.")
    return True


def create_submit_dir():
    """Copy source files to staging directory."""
    if os.path.exists(OUTPUT_DIR):
        shutil.rmtree(OUTPUT_DIR)
    os.makedirs(OUTPUT_DIR)

    for f in SOURCES:
        src = os.path.join(SRC_DIR, f)
        dst = os.path.join(OUTPUT_DIR, f)
        shutil.copy2(src, dst)
        print(f"  {f}")

    # jsoncpp/ subdirectory
    jsoncpp_dir = os.path.join(OUTPUT_DIR, "jsoncpp")
    os.makedirs(jsoncpp_dir, exist_ok=True)
    for f in JSONCPP:
        src = os.path.join(SRC_DIR, f)
        if "jsoncpp" in f and not f.startswith("jsoncpp"):
            # jsoncpp.cpp is at botzone/jsoncpp.cpp, not botzone/jsoncpp/jsoncpp.cpp
            dst = os.path.join(OUTPUT_DIR, f)
        else:
            dst = os.path.join(OUTPUT_DIR, f)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(src, dst)
        print(f"  {f}")

    return True


def create_zip():
    """Create botzone_submit.zip from staging directory."""
    zip_path = os.path.join(SCRIPT_DIR, "..", "botzone_submit.zip")
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        for root, dirs, files in os.walk(OUTPUT_DIR):
            for file in files:
                full_path = os.path.join(root, file)
                arc_name = os.path.relpath(full_path, OUTPUT_DIR)
                zf.write(full_path, arc_name)
    size_kb = os.path.getsize(zip_path) / 1024
    print(f"\n  Zip created: botzone_submit.zip ({size_kb:.0f} KB)")
    return zip_path


def create_amalgamation():
    """Concatenate all sources into a single bot.cpp for easy pasting."""
    output_path = os.path.join(SCRIPT_DIR, "..", "bot_amalgamated.cpp")
    lines = []

    lines.append("// ============================================================")
    lines.append("// DouEnMH Amalgamated Bot — Paste into Botzone editor")
    lines.append("// Generated by prepare_botzone.py --amalgamate")
    lines.append("// ============================================================")
    lines.append("")

    # All local headers that will be inlined (strip their #includes)
    ALL_INLINED = AMALGAMATE_ORDER + AMALGAMATE_CPP

    # First: jsoncpp (must come before any usage)
    jsoncpp_cpp = os.path.join(SRC_DIR, "jsoncpp.cpp")
    with open(jsoncpp_cpp, 'r', encoding='utf-8') as f:
        content = f.read()
    lines.append("// ============================================================")
    lines.append("// jsoncpp.cpp (amalgamated)")
    lines.append("// ============================================================")
    lines.append(content)
    lines.append("")

    # Then all headers in dependency order
    for f in AMALGAMATE_ORDER:
        path = os.path.join(SRC_DIR, f)
        with open(path, 'r', encoding='utf-8') as fh:
            content = fh.read()
        lines.append(f"// ============================================================")
        lines.append(f"// {f}")
        lines.append(f"// ============================================================")
        filtered = []
        for line in content.split('\n'):
            stripped = line.strip()
            # Strip jsoncpp includes (already above)
            if stripped.startswith('#include "jsoncpp/json.h"'):
                continue
            # Strip includes to other inlined files
            if any(stripped.startswith(f'#include "{h}"') for h in ALL_INLINED):
                continue
            filtered.append(line)
        lines.extend(filtered)
        lines.append("")

    # Then: .cpp implementation files (oracle.cpp)
    for f in AMALGAMATE_CPP:
        path = os.path.join(SRC_DIR, f)
        with open(path, 'r', encoding='utf-8') as fh:
            content = fh.read()
        lines.append(f"// ============================================================")
        lines.append(f"// {f} (amalgamated)")
        lines.append(f"// ============================================================")
        filtered = []
        for line in content.split('\n'):
            stripped = line.strip()
            # Strip includes to inlined files
            if any(stripped.startswith(f'#include "{h}"') for h in ALL_INLINED):
                continue
            filtered.append(line)
        lines.extend(filtered)
        lines.append("")

    # Finally: main.cpp (without its local #includes)
    main_path = os.path.join(SRC_DIR, "main.cpp")
    with open(main_path, 'r', encoding='utf-8') as f:
        content = f.read()
    lines.append("// ============================================================")
    lines.append("// main.cpp")
    lines.append("// ============================================================")
    filtered = []
    for line in content.split('\n'):
        stripped = line.strip()
        if any(stripped.startswith(f'#include "{h}"') for h in ALL_INLINED + ["jsoncpp/json.h"]):
            continue
        filtered.append(line)
    lines.extend(filtered)

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

    size_kb = os.path.getsize(output_path) / 1024
    print(f"\n  Amalgamation created: bot_amalgamated.cpp ({size_kb:.0f} KB)")
    print(f"  Paste contents into Botzone editor (single file).")
    return output_path


def print_instructions():
    print(f"""
{'='*60}
Botzone Submission Instructions
{'='*60}

1. Compiler Option:
   When submitting on Botzone, select the "带很多库" compiler.
   This provides LibTorch 1.5.0 + jsoncpp + Eigen.

2. Model Files (upload to Botzone User Storage):
""")
    for m in MODEL_FILES:
        size_str = ""
        model_path = os.path.join(
            SCRIPT_DIR, "..", "..", "..", "environments", "model_exports", m)
        if os.path.exists(model_path):
            size_mb = os.path.getsize(model_path) / (1024 * 1024)
            size_str = f"({size_mb:.1f} MB)"
        print(f"   - {m}  {size_str}")

    print(f"""
   Total model size: ~210 MB (3 bid + 3 play)
   Ensure User Storage has enough space.

3. Submit:
   - Upload botzone_submit.zip as source code
   - Select "带很多库" compiler
   - If using amalgamated single file: paste bot_amalgamated.cpp

4. Source Code Configuration:
   - MODEL_DIR = "data/models"  (Botzone storage path)
   - Upload .pt files to User Storage → models/ folder

{'='*60}
""")


def main():
    amalgamate = "--amalgamate" in sys.argv
    check_only = "--check" in sys.argv

    print("=" * 60)
    print("DouMH Botzone Submission Preparation")
    print("=" * 60)
    print()

    if not check_files():
        sys.exit(1)

    if check_only:
        return

    if amalgamate:
        print("\nCreating amalgamated source...")
        create_amalgamation()
    else:
        print("\nCreating submission directory...")
        create_submit_dir()
        create_zip()

    print_instructions()


if __name__ == "__main__":
    main()
